import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EPOCH_PATH = 'src/sim/rulesEpoch.js';
const GENERATION_PATH = 'src/sim/generation.js';

function slash(file) {
  return file.split(path.sep).join('/');
}

function isProductionSimFile(relativePath) {
  const file = slash(relativePath);
  return (
    file.startsWith('src/sim/')
    && file.endsWith('.js')
    && !file.endsWith('.test.js')
    && !file.endsWith('.bench.js')
    && file !== EPOCH_PATH
  );
}

async function walk(directory, root, out) {
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      await walk(absolute, root, out);
    } else {
      const relative = path.relative(root, absolute);
      if (isProductionSimFile(relative)) out.push(slash(relative));
    }
  }
}

export async function rulesFiles(root = REPO_ROOT) {
  const files = [];
  await walk(path.join(root, 'src', 'sim'), root, files);
  files.push('src/app/sim.worker.js');
  return files.sort();
}

export async function computeRulesHash(root = REPO_ROOT) {
  const hash = createHash('sha256');
  for (const relative of await rulesFiles(root)) {
    const source = await readFile(path.join(root, relative), 'utf8');
    hash.update(relative);
    hash.update('\0');
    hash.update(source.replace(/\r\n?/g, '\n'));
    hash.update('\0');
  }
  return hash.digest('hex');
}

function integerExport(source, name) {
  const match = source.match(new RegExp(`export\\s+const\\s+${name}\\s*=\\s*(\\d+)\\s*;`));
  return match ? Number(match[1]) : null;
}

function stringExport(source, name) {
  const match = source.match(new RegExp(`export\\s+const\\s+${name}\\s*=\\s*['"]([0-9a-f]+)['"]\\s*;`, 'i'));
  return match?.[1]?.toLowerCase() ?? null;
}

export async function readRulesState(root = REPO_ROOT) {
  const [generationSource, epochSource] = await Promise.all([
    readFile(path.join(root, GENERATION_PATH), 'utf8'),
    readFile(path.join(root, EPOCH_PATH), 'utf8'),
  ]);
  const generation = integerExport(generationSource, 'SIM_GENERATION');
  const epochGeneration = integerExport(epochSource, 'SIM_RULES_GENERATION');
  const epochHash = stringExport(epochSource, 'SIM_RULES_SHA256');
  if (!Number.isInteger(generation)) throw new Error(`Cannot read SIM_GENERATION from ${GENERATION_PATH}`);
  if (!Number.isInteger(epochGeneration) || !/^[0-9a-f]{64}$/.test(epochHash ?? '')) {
    throw new Error(`Cannot read the committed rules epoch from ${EPOCH_PATH}`);
  }
  return { generation, epochGeneration, epochHash };
}

function epochSource(generation, hash) {
  return `// Generated by scripts/check-sim-rules.mjs --write after an intentional generation bump.\n`
    + `export const SIM_RULES_GENERATION = ${generation};\n`
    + `export const SIM_RULES_SHA256 = '${hash}';\n`;
}

export async function checkRules({ root = REPO_ROOT, write = false } = {}) {
  const hash = await computeRulesHash(root);
  const state = await readRulesState(root);
  const current = state.generation === state.epochGeneration && hash === state.epochHash;
  if (current) return { ...state, hash, changed: false };

  if (!write) {
    if (state.generation !== state.epochGeneration) {
      throw new Error(
        `Simulation generation ${state.generation} does not match committed rules generation `
        + `${state.epochGeneration}. Run "npm run sim-rules:write" after an intentional bump.`,
      );
    }
    throw new Error(
      `Deterministic simulation sources changed without advancing SIM_GENERATION `
      + `(${state.generation}). Bump it, then run "npm run sim-rules:write".`,
    );
  }

  if (state.generation <= state.epochGeneration) {
    throw new Error(
      `Refusing to rewrite deterministic rules at generation ${state.generation}. `
      + `Advance SIM_GENERATION above ${state.epochGeneration} first.`,
    );
  }
  await writeFile(
    path.join(root, EPOCH_PATH),
    epochSource(state.generation, hash),
    'utf8',
  );
  return { ...state, epochGeneration: state.generation, epochHash: hash, hash, changed: true };
}
